-- Evolución del modelo relacional:
-- 1. Ampliación de Venue con 'city'
-- 2. Borrado lógico en Event con 'active'
-- 3. Relación Event -> Venue (ManyToOne obligatoria)
-- 4. Nueva entidad Category
-- 5. Relación Event <-> Category (ManyToMany con tabla events_categories)
-- 6. Índices para optimización de filtros y ordenamiento
-- 7. Inserción de las 7 categorías iniciales representativas
-- ========================================================================

-- 1. Ampliación de venues con columna city (obligatoria y con migración segura de datos existentes)
ALTER TABLE venues ADD COLUMN city VARCHAR(100);
UPDATE venues SET city = 'Barranquilla' WHERE city IS NULL;
ALTER TABLE venues ALTER COLUMN city SET NOT NULL;

-- 2. Incorporación de active en events para borrado lógico (por defecto activo)
ALTER TABLE events ADD COLUMN active BOOLEAN DEFAULT TRUE NOT NULL;

-- 3. Relación obligatoria Event -> Venue
ALTER TABLE events ADD COLUMN venue_id BIGINT;
-- Si existían eventos previos sin sede, se asocian a la primera sede disponible
UPDATE events SET venue_id = (SELECT MIN(id) FROM venues) WHERE venue_id IS NULL;
-- En caso de no existir sedes en una base vacía no afecta; cuando existan eventos se requiere venue_id
ALTER TABLE events ALTER COLUMN venue_id SET NOT NULL;
ALTER TABLE events ADD CONSTRAINT fk_events_venues FOREIGN KEY (venue_id) REFERENCES venues(id);

-- 4. Nueva entidad Category
CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(255)
);

-- 5. Tabla intermedia para relación ManyToMany Event <-> Category
CREATE TABLE events_categories (
    event_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,
    PRIMARY KEY (event_id, category_id),
    CONSTRAINT fk_ec_event FOREIGN KEY (event_id) REFERENCES events(id) ON DELETE CASCADE,
    CONSTRAINT fk_ec_category FOREIGN KEY (category_id) REFERENCES categories(id) ON DELETE RESTRICT
);

-- 6. Índices de rendimiento para filtros y orden cronológico
CREATE INDEX idx_events_fecha_id ON events(fecha DESC, id DESC);
CREATE INDEX idx_events_venue_id ON events(venue_id);
CREATE INDEX idx_events_active ON events(active);
CREATE INDEX idx_venues_city ON venues(city);
CREATE INDEX idx_events_nombre ON events(nombre);
CREATE INDEX idx_categories_name ON categories(name);

